//! Stages the built UI (`ui/dist`) into `$OUT_DIR/ui` for embedding.
//!
//! Layout of `$OUT_DIR/ui`:
//! - `raw/<path>`: every file of the UI build, byte for byte.
//! - `br/<path>`, `gz/<path>`: brotli (quality 11) and gzip (level 9) variants of text
//!   files, written only with the `precompressed` feature and only when they are at least
//!   5 % smaller than the original.
//!
//! It also writes `$OUT_DIR/codegen_assets.rs`, a static table of `include_bytes!` entries
//! with build-time ETags, used by the `backend-codegen` feature.
//!
//! The source directory is `../../ui/dist`, overridable with the `SPIKE_UI_DIST`
//! environment variable (used to build the empty-UI and synthetic-bundle variants).
#![forbid(unsafe_code)]

#[allow(dead_code)]
#[path = "src/mime.rs"]
mod mime;

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-env-changed=SPIKE_UI_DIST");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/mime.rs");

    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let src = env::var_os("SPIKE_UI_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("../../ui/dist"));
    let src = if src.is_relative() {
        manifest_dir.join(src)
    } else {
        src
    };
    assert!(
        src.is_dir(),
        "UI build not found at {}: run `npm run build` in ui/ or set SPIKE_UI_DIST",
        src.display()
    );
    println!("cargo:rerun-if-changed={}", src.display());

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let stage = out_dir.join("ui");
    if stage.exists() {
        fs::remove_dir_all(&stage).expect("clean staging dir");
    }
    fs::create_dir_all(stage.join("raw")).expect("create staging dir");
    let precompress = env::var_os("CARGO_FEATURE_PRECOMPRESSED").is_some();

    let mut files = Vec::new();
    collect(&src, &src, &mut files);
    files.sort();

    let mut codegen =
        String::from("// Generated by build.rs. Do not edit.\npub static FILES: &[GenFile] = &[\n");
    for rel in &files {
        let bytes = fs::read(src.join(rel)).expect("read UI file");
        let raw_path = write_staged(&stage, "raw", rel, &bytes);
        let etag = format!("{:016x}", xxhash_rust::xxh3::xxh3_64(&bytes));

        let (mut br_path, mut gz_path) = (None, None);
        if precompress && mime::is_compressible(rel) {
            let br = brotli_compress(&bytes);
            if worth_it(br.len(), bytes.len()) {
                br_path = Some(write_staged(&stage, "br", rel, &br));
            }
            let gz = gzip_compress(&bytes);
            if worth_it(gz.len(), bytes.len()) {
                gz_path = Some(write_staged(&stage, "gz", rel, &gz));
            }
        }
        let opt = |p: Option<PathBuf>| match p {
            Some(p) => format!(
                "Some(include_bytes!({:?}))",
                p.to_str().expect("utf-8 path")
            ),
            None => "None".to_owned(),
        };
        writeln!(
            codegen,
            "    GenFile {{ path: {rel:?}, etag: {etag:?}, identity: include_bytes!({raw:?}), br: {br}, gzip: {gz} }},",
            raw = raw_path.to_str().expect("utf-8 path"),
            br = opt(br_path),
            gz = opt(gz_path),
        )
        .expect("write to string");
    }
    codegen.push_str("];\n");
    fs::write(out_dir.join("codegen_assets.rs"), codegen).expect("write codegen_assets.rs");
}

/// Recursively collects regular files below `dir` as `/`-separated paths relative to `root`.
fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in fs::read_dir(dir).expect("read UI dir") {
        let entry = entry.expect("dir entry");
        let path = entry.path();
        let kind = entry.file_type().expect("file type");
        if kind.is_dir() {
            collect(root, &path, out);
        } else if kind.is_file() {
            let rel = path.strip_prefix(root).expect("below root");
            let rel: Vec<&str> = rel
                .iter()
                .map(|c| c.to_str().expect("utf-8 file name"))
                .collect();
            out.push(rel.join("/"));
        }
    }
}

fn write_staged(stage: &Path, variant: &str, rel: &str, bytes: &[u8]) -> PathBuf {
    let path = stage.join(variant).join(rel);
    fs::create_dir_all(path.parent().expect("parent")).expect("create dir");
    fs::write(&path, bytes).expect("write staged file");
    path
}

/// A compressed variant is kept only when it saves at least 5 %.
fn worth_it(compressed: usize, original: usize) -> bool {
    compressed * 100 <= original * 95
}

fn brotli_compress(input: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(input.len() / 3 + 64);
    {
        let mut w = brotli::CompressorWriter::new(&mut out, 64 * 1024, 11, 22);
        w.write_all(input).expect("brotli");
        w.flush().expect("brotli flush");
    }
    out
}

fn gzip_compress(input: &[u8]) -> Vec<u8> {
    let mut enc = flate2::write::GzEncoder::new(
        Vec::with_capacity(input.len() / 3 + 64),
        flate2::Compression::best(),
    );
    enc.write_all(input).expect("gzip");
    enc.finish().expect("gzip finish")
}
