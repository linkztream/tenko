//! The embedded asset table.
//!
//! `build.rs` stages the UI build, compresses it and generates a static table of
//! `include_bytes!` entries ([`GenFile`]) with the content hash of every file. At first use
//! the table is turned into an [`AssetTable`] with every header value precomputed, so serving
//! a file is a hash lookup plus a reference-count increment on a `&'static [u8]`.

use std::collections::HashMap;
use std::fmt;
use std::sync::{Arc, OnceLock};

use axum::http::HeaderValue;
use bytes::Bytes;
use sha2::{Digest, Sha256};

use super::mime;

/// Prefix of content-hashed build output (Vite `build.assetsDir`).
const IMMUTABLE_PREFIX: &str = "assets/";

/// `Cache-Control` for content-hashed files.
static CACHE_IMMUTABLE: HeaderValue =
    HeaderValue::from_static("public, max-age=31536000, immutable");
/// `Cache-Control` for everything else (`index.html`): always revalidate with the `ETag`.
static CACHE_REVALIDATE: HeaderValue = HeaderValue::from_static("no-cache");

/// One entry of the table generated by `build.rs`.
pub struct GenFile {
    /// Path relative to the UI root, `/`-separated (`assets/index-abc123.js`).
    pub path: &'static str,
    /// First 16 lowercase hex characters of the SHA-256 of `identity`.
    pub etag: &'static str,
    /// The file, byte for byte.
    pub identity: &'static [u8],
    /// Brotli variant, present when it is at least 5 % smaller.
    pub br: Option<&'static [u8]>,
    /// Gzip variant, present when it is at least 5 % smaller.
    pub gzip: Option<&'static [u8]>,
}

include!(concat!(env!("OUT_DIR"), "/ui_assets.rs"));

/// One servable file with its encoded variants and precomputed headers.
pub struct Asset {
    /// The file, byte for byte.
    pub identity: Bytes,
    /// Brotli variant, if one was worth keeping.
    pub br: Option<Bytes>,
    /// Gzip variant, if one was worth keeping.
    pub gzip: Option<Bytes>,
    /// `Content-Type`, from the file extension.
    pub content_type: HeaderValue,
    /// `Cache-Control`: immutable under `assets/`, `no-cache` everywhere else.
    pub cache_control: HeaderValue,
    /// Hex content hash without quotes; the base of the per-encoding `ETag` values.
    pub etag_base: Box<str>,
    /// `ETag` of the identity representation.
    pub etag_identity: HeaderValue,
    /// `ETag` of the brotli representation.
    pub etag_br: HeaderValue,
    /// `ETag` of the gzip representation.
    pub etag_gzip: HeaderValue,
}

impl Asset {
    fn new(
        path: &str,
        identity: Bytes,
        br: Option<Bytes>,
        gzip: Option<Bytes>,
        etag_hex: &str,
    ) -> Self {
        let etag = |suffix: &str| {
            HeaderValue::from_str(&format!("\"{etag_hex}{suffix}\""))
                .expect("a hex ETag is a valid header value")
        };
        Self {
            identity,
            br,
            gzip,
            content_type: HeaderValue::from_static(mime::content_type(path)),
            cache_control: if path.starts_with(IMMUTABLE_PREFIX) {
                CACHE_IMMUTABLE.clone()
            } else {
                CACHE_REVALIDATE.clone()
            },
            etag_base: etag_hex.into(),
            etag_identity: etag(""),
            etag_br: etag(".br"),
            etag_gzip: etag(".gz"),
        }
    }

    /// Whether a brotli or gzip variant exists, i.e. whether responses must vary on
    /// `Accept-Encoding`.
    pub fn has_variants(&self) -> bool {
        self.br.is_some() || self.gzip.is_some()
    }
}

impl fmt::Debug for Asset {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Asset")
            .field("content_type", &self.content_type)
            .field("cache_control", &self.cache_control)
            .field("etag_base", &self.etag_base)
            .field("identity_len", &self.identity.len())
            .field("br_len", &self.br.as_ref().map(Bytes::len))
            .field("gzip_len", &self.gzip.as_ref().map(Bytes::len))
            .finish_non_exhaustive()
    }
}

/// Summary of a table, for the start-up log line.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TableStats {
    /// Number of files.
    pub files: usize,
    /// Total size of the identity representations in bytes.
    pub identity_bytes: usize,
    /// Number of files with a brotli variant.
    pub br_files: usize,
    /// Number of files with a gzip variant.
    pub gzip_files: usize,
}

/// All embedded files, keyed by their path relative to the UI root (`index.html`,
/// `assets/index-abc123.js`).
pub struct AssetTable {
    files: HashMap<Box<str>, Asset>,
}

impl AssetTable {
    /// The table generated at build time from the UI build (or the placeholder UI, see
    /// [`AssetTable::is_stub`]). Built on first use and shared afterwards.
    pub fn embedded() -> Arc<Self> {
        static TABLE: OnceLock<Arc<AssetTable>> = OnceLock::new();
        Arc::clone(TABLE.get_or_init(|| {
            let files = FILES
                .iter()
                .map(|f| {
                    let asset = Asset::new(
                        f.path,
                        Bytes::from_static(f.identity),
                        f.br.map(Bytes::from_static),
                        f.gzip.map(Bytes::from_static),
                        f.etag,
                    );
                    (Box::from(f.path), asset)
                })
                .collect();
            Arc::new(Self { files })
        }))
    }

    /// Builds a table from `(path, identity, brotli, gzip)` entries; the paths are relative to
    /// the UI root and `/`-separated, without a leading slash. The `ETag` base is computed
    /// here with the rule `build.rs` uses (first 16 hex characters of the SHA-256 of the
    /// identity bytes). The variant payloads are served as they are, never decoded. Meant for
    /// tests and tools; a later entry replaces an earlier one with the same path.
    pub fn from_files(files: Vec<(String, Bytes, Option<Bytes>, Option<Bytes>)>) -> Self {
        let files = files
            .into_iter()
            .map(|(path, identity, br, gzip)| {
                let etag = etag_base(&identity);
                let asset = Asset::new(&path, identity, br, gzip, &etag);
                (path.into_boxed_str(), asset)
            })
            .collect();
        Self { files }
    }

    /// Looks up a file by its path relative to the UI root.
    pub fn get(&self, path: &str) -> Option<&Asset> {
        self.files.get(path)
    }

    /// `index.html`, the entry point and the fallback of client-side routes.
    pub fn index_html(&self) -> Option<&Asset> {
        self.files.get("index.html")
    }

    /// The paths of all files, in no particular order.
    pub fn paths(&self) -> impl Iterator<Item = &str> {
        self.files.keys().map(|k| &**k)
    }

    /// File counts and sizes.
    pub fn stats(&self) -> TableStats {
        TableStats {
            files: self.files.len(),
            identity_bytes: self.files.values().map(|a| a.identity.len()).sum(),
            br_files: self.files.values().filter(|a| a.br.is_some()).count(),
            gzip_files: self.files.values().filter(|a| a.gzip.is_some()).count(),
        }
    }

    /// Whether the embedded table holds the placeholder page of a `TENKO_UI_STUB=1` build
    /// instead of the real UI.
    pub const fn is_stub() -> bool {
        cfg!(tenko_ui_stub)
    }
}

impl fmt::Debug for AssetTable {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("AssetTable")
            .field("stats", &self.stats())
            .finish()
    }
}

/// The first 16 lowercase hex characters of the SHA-256 of `bytes`.
fn etag_base(bytes: &[u8]) -> String {
    use fmt::Write as _;
    let digest = Sha256::digest(bytes);
    let mut hex = String::with_capacity(16);
    for byte in digest.iter().take(8) {
        write!(hex, "{byte:02x}").expect("write to string");
    }
    hex
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(path: &str, body: &'static [u8]) -> (String, Bytes, Option<Bytes>, Option<Bytes>) {
        (path.to_owned(), Bytes::from_static(body), None, None)
    }

    #[test]
    fn etag_is_sixteen_hex_characters_of_sha256() {
        // SHA-256 of the empty input is e3b0c44298fc1c14...
        assert_eq!(etag_base(b""), "e3b0c44298fc1c14");
        // SHA-256 of "abc" is ba7816bf8f01cfea...
        assert_eq!(etag_base(b"abc"), "ba7816bf8f01cfea");
    }

    #[test]
    fn from_files_computes_headers() {
        let table = AssetTable::from_files(vec![
            entry("index.html", b"<!doctype html>"),
            (
                "assets/app-1.js".to_owned(),
                Bytes::from_static(b"let a = 1;"),
                Some(Bytes::from_static(b"br")),
                Some(Bytes::from_static(b"gz")),
            ),
            entry("assets/logo-1.png", b"\x89PNG"),
            entry("favicon.ico", b"ico"),
        ]);

        let index = table.index_html().expect("index.html");
        assert_eq!(index.content_type, "text/html; charset=utf-8");
        assert_eq!(index.cache_control, "no-cache");
        assert!(!index.has_variants());
        assert_eq!(index.etag_base.len(), 16);
        assert_eq!(
            index.etag_identity.to_str().unwrap(),
            format!("\"{}\"", index.etag_base)
        );
        assert_eq!(
            index.etag_br.to_str().unwrap(),
            format!("\"{}.br\"", index.etag_base)
        );
        assert_eq!(
            index.etag_gzip.to_str().unwrap(),
            format!("\"{}.gz\"", index.etag_base)
        );

        let js = table.get("assets/app-1.js").expect("js");
        assert_eq!(js.content_type, "text/javascript; charset=utf-8");
        assert_eq!(js.cache_control, "public, max-age=31536000, immutable");
        assert!(js.has_variants());

        // Only the `assets/` prefix is immutable, whatever the extension.
        assert_eq!(table.get("favicon.ico").unwrap().cache_control, "no-cache");
        assert_eq!(
            table.get("assets/logo-1.png").unwrap().content_type,
            "image/png"
        );
        assert!(table.get("assets/missing.js").is_none());

        let mut paths: Vec<&str> = table.paths().collect();
        paths.sort_unstable();
        assert_eq!(
            paths,
            [
                "assets/app-1.js",
                "assets/logo-1.png",
                "favicon.ico",
                "index.html"
            ]
        );

        let stats = table.stats();
        assert_eq!(
            stats,
            TableStats {
                files: 4,
                identity_bytes: "<!doctype html>".len() + "let a = 1;".len() + 4 + 3,
                br_files: 1,
                gzip_files: 1,
            }
        );
    }

    #[test]
    fn identical_content_has_identical_etag() {
        let table = AssetTable::from_files(vec![
            entry("a.txt", b"same"),
            entry("b.txt", b"same"),
            entry("c.txt", b"different"),
        ]);
        assert_eq!(
            table.get("a.txt").unwrap().etag_base,
            table.get("b.txt").unwrap().etag_base
        );
        assert_ne!(
            table.get("a.txt").unwrap().etag_base,
            table.get("c.txt").unwrap().etag_base
        );
    }

    #[test]
    fn embedded_table_is_shared_and_has_the_entry_point() {
        let table = AssetTable::embedded();
        assert!(Arc::ptr_eq(&table, &AssetTable::embedded()));
        let index = table
            .index_html()
            .expect("the embedded UI has an index.html");
        assert_eq!(index.cache_control, "no-cache");
        assert_eq!(index.content_type, "text/html; charset=utf-8");
    }

    #[test]
    fn embedded_table_agrees_with_run_time_hashing() {
        // The ETag base comes from build.rs; `from_files` must derive the same value.
        let table = AssetTable::embedded();
        for path in table.paths() {
            let asset = table.get(path).unwrap();
            let again =
                AssetTable::from_files(vec![(path.to_owned(), asset.identity.clone(), None, None)]);
            assert_eq!(
                asset.etag_base,
                again.get(path).unwrap().etag_base,
                "{path}"
            );
            assert_eq!(
                asset.content_type,
                again.get(path).unwrap().content_type,
                "{path}"
            );
            assert_eq!(
                asset.cache_control,
                again.get(path).unwrap().cache_control,
                "{path}"
            );
        }
    }

    #[test]
    fn embedded_variants_are_smaller_and_html_is_compressed() {
        let table = AssetTable::embedded();
        for path in table.paths() {
            let asset = table.get(path).unwrap();
            for variant in [&asset.br, &asset.gzip].into_iter().flatten() {
                // Kept only when at least 5 % smaller.
                assert!(variant.len() * 100 <= asset.identity.len() * 95, "{path}");
            }
        }
        // Stub builds exercise the same code path as real ones: the entry point is compressed.
        if AssetTable::is_stub() {
            let index = table.index_html().unwrap();
            assert!(index.br.is_some() && index.gzip.is_some());
        }
        let stats = table.stats();
        assert!(stats.files >= 2 && stats.identity_bytes > 0 && stats.br_files >= 1);
    }
}
