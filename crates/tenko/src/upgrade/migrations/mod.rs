//! The migration registry of the data-directory format (OPS-23).
//!
//! [`CURRENT`] is the format this binary writes. Every change to stored data (a new field
//! that older code cannot read, a renamed table, a changed key or value encoding, a change
//! of the store's own files) raises it by one and adds exactly one migration from the
//! previous format, in a file of its own beside this one, plus a compatibility fixture
//! (`docs/upgrades.md` describes the convention). Adding format 2 takes three edits:
//!
//! 1. a file `v2.rs` with a type that implements [`Migration`] (`to()` returns 2);
//! 2. `mod v2;` here and `&v2::V2` in [`MIGRATIONS`], and a [`FormatInfo`] line in
//!    [`FORMATS`];
//! 3. `CURRENT = 2`, and a fixture `crates/tenko/tests/fixtures/datadir/v2/` generated by
//!    the new binary (the v1 fixture stays and keeps proving that format 1 migrates).
//!
//! A migration plans the mutations of one write batch against a view of the store at the
//! previous format; the runner ([`super::datadir`]) adds the bump of the stored format
//! record and an audit record to the same batch, so the data and its format number change
//! together or not at all. The runner copies the closed store first; that copy is the
//! rollback point. A migration whose batch would exceed the store's batch limit (16 MiB)
//! must split its work into idempotent batches and leave the bump to the last one; none
//! does yet.

use tenko_store::{Mutation, ReadView, StoreError};

/// The data-directory format this binary writes and reads.
pub const CURRENT: u32 = 1;

/// The format of a data directory written before format versions existed: it has neither
/// a marker file nor a stored format record.
pub const INITIAL: u32 = 1;

/// One documented format.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FormatInfo {
    /// The format version.
    pub version: u32,
    /// The first release that writes it.
    pub since: &'static str,
    /// What changed, in English.
    pub summary: &'static str,
}

/// Every format this binary knows, oldest first; the last one is [`CURRENT`].
pub const FORMATS: &[FormatInfo] = &[FormatInfo {
    version: 1,
    since: "0.1.0",
    summary: "the initial format: the replicated store (log.redb, the state file behind \
              sm.current, snapshots/), the format marker and the sys.format record",
}];

/// A migration failed to plan.
#[derive(Debug)]
pub enum MigrationError {
    /// A read of the store failed.
    Store(StoreError),
    /// The stored data cannot be migrated, with the reason.
    Data(String),
}

impl std::fmt::Display for MigrationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Store(error) => write!(f, "store read failed: {error}"),
            Self::Data(reason) => f.write_str(reason),
        }
    }
}

impl std::error::Error for MigrationError {}

impl From<StoreError> for MigrationError {
    fn from(error: StoreError) -> Self {
        Self::Store(error)
    }
}

/// One step of the format: from `to() - 1` to `to()`.
pub trait Migration: Send + Sync {
    /// The format this migration produces; it runs on a store at `to() - 1`.
    fn to(&self) -> u32;

    /// What the migration does, in English, for the log and `tenko upgrade check`.
    fn summary(&self) -> &'static str;

    /// The mutations that turn the data of `view` (at format `to() - 1`) into format
    /// `to()`. The runner commits them in one batch with the bump of the stored format.
    ///
    /// # Errors
    ///
    /// [`MigrationError`] when the data cannot be read or migrated.
    fn plan(&self, view: &dyn ReadView) -> Result<Vec<Mutation>, MigrationError>;
}

/// The migrations, in order: entry `i` migrates from `INITIAL + i` to `INITIAL + i + 1`.
pub static MIGRATIONS: &[&dyn Migration] = &[];

/// A set of migrations up to a current format: [`Registry::builtin`] in the binary, other
/// sets in tests.
#[derive(Clone, Copy)]
pub struct Registry<'a> {
    /// The format the registry migrates to.
    pub current: u32,
    /// The migrations, in order, as [`MIGRATIONS`].
    pub migrations: &'a [&'a dyn Migration],
}

impl std::fmt::Debug for Registry<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Registry")
            .field("current", &self.current)
            .field("migrations", &self.migrations.len())
            .finish()
    }
}

impl Registry<'static> {
    /// The registry of this binary.
    pub fn builtin() -> Self {
        Self {
            current: CURRENT,
            migrations: MIGRATIONS,
        }
    }
}

impl<'a> Registry<'a> {
    /// The migration that produces format `to`.
    pub fn migration(&self, to: u32) -> Option<&'a dyn Migration> {
        self.migrations
            .iter()
            .copied()
            .find(|migration| migration.to() == to)
    }

    /// The migrations from `from` to the current format, in order; `None` when one is
    /// missing.
    pub fn path(&self, from: u32) -> Option<Vec<&'a dyn Migration>> {
        ((from + 1)..=self.current)
            .map(|to| self.migration(to))
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_registry_is_continuous_up_to_the_current_format() {
        assert_eq!(
            usize::try_from(CURRENT - INITIAL).expect("small"),
            MIGRATIONS.len()
        );
        for (index, migration) in MIGRATIONS.iter().enumerate() {
            let expected = INITIAL + 1 + u32::try_from(index).expect("small");
            assert_eq!(migration.to(), expected, "{}", migration.summary());
        }
        assert!(Registry::builtin().path(INITIAL).is_some());
        assert_eq!(
            Registry::builtin().path(CURRENT).map(|path| path.len()),
            Some(0)
        );
    }

    #[test]
    fn every_format_is_documented_once_in_order() {
        let versions: Vec<u32> = FORMATS.iter().map(|format| format.version).collect();
        let expected: Vec<u32> = (INITIAL..=CURRENT).collect();
        assert_eq!(versions, expected);
        assert!(FORMATS.iter().all(|format| !format.summary.is_empty()));
    }
}
