//! The migration registry of the data-directory format (OPS-23).
//!
//! [`CURRENT`] is the format this binary writes. Every change to stored data (a new field
//! that older code cannot read, a renamed table, a changed key or value encoding, a change
//! of the store's own files) raises it by one and adds exactly one migration from the
//! previous format, in a file of its own beside this one, plus a compatibility fixture
//! (`docs/upgrades.md` describes the convention). Format 2 is the Slice 3 contract format
//! and format 3 the Phase 2 contract format: empty migrations (`v2.rs`, `v3.rs`) that only
//! keep an older binary away from new stored values; format 4 is the Phase 3 contract format
//! (`v4.rs`, WP7.0), empty as well; format 5 (`v5.rs`, WP9.2) the stored role
//! `dhcp_pd_pool` of IPAM ranges, empty as well; format 6 (`v6.rs`, WP14.0 and WP13.0) the
//! contract format of Phase 4 and of Slice 13 (the `migrate` namespace, the object kinds
//! `mirror` and `takeover`, the token scope `mirror:<id>` and the `kerberos` entry of a DNS
//! access list), empty as well; format 7 (`v7.rs`) the contracts of the cluster recovery
//! (the generation record and the superseded marks), empty as well. Adding format 8 takes
//! three edits:
//!
//! 1. a file `v8.rs` with a type that implements [`Migration`] (`to()` returns 8);
//! 2. `mod v8;` here and `&v8::V8` in [`MIGRATIONS`], and a [`FormatInfo`] line in
//!    [`FORMATS`];
//! 3. `CURRENT = 8`, and a fixture `crates/tenko/tests/fixtures/datadir/v8/` generated by
//!    the new binary (the fixtures of the earlier formats stay and keep proving that those
//!    formats migrate).
//!
//! A migration plans the mutations of one write batch against a view of the store at the
//! previous format; the runner ([`super::datadir`]) adds the bump of the stored format
//! record and an audit record to the same batch, so the data and its format number change
//! together or not at all. The runner copies the closed store first; that copy is the
//! rollback point. A migration whose batch would exceed the store's batch limit (16 MiB)
//! must split its work into idempotent batches and leave the bump to the last one; none
//! does yet.

